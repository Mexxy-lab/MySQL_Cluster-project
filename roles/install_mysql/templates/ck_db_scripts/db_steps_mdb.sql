select '------------------ Quiescing Slave ------------------';
show variables like 'hostname'; show global variables like 'port';
set global sync_relay_log=1, global sync_relay_log_info=1, global sync_master_info=1;
select 'Stopping slave: ', current_time();
stop slave sql_thread;
select 'Snapshot starts: ', current_time();
select 'Flushing tables: ';
flush tables with read lock;
select sleep(10);
select '----------- Recording Master/Slave Statuses ---------';
select 'Master status: ', current_time();
show master status;
select ' ';
select 'Master Log Read Info: ';
select 'Master_Log_Name    Master_Log_Position_Read';
select Master_log_name, Master_log_pos from mysql.slave_master_info;
select ' ';
select 'Relay/Master Log Exec Info: ';
select 'Relay_Log_Name  Relay_Position_Exec  Master_Log  Master_Log_Position_Exec';
select Relay_log_name, Relay_log_pos, Master_log_name, Master_log_pos from mysql.slave_relay_log_info;
select ' ';
select sleep(5);
select 'Slave Status: ', current_time();
show slave status;
set global sync_relay_log=DEFAULT, global sync_relay_log_info=DEFAULT, global sync_master_info=DEFAULT;
select '------------------------------------------------------';
select 'Snapshot ends: ', current_time();
unlock tables;
select 'Starting slave';
start slave sql_thread;
select '------------------------------------------------------';
